@triton.jit
def native_xor(x,lane,offset:tl.constexpr):
    raw=native_bpermute(((lane^offset)<<2).to(tl.int32),x.to(tl.int32,bitcast=True))
    return raw.to(tl.float32,bitcast=True)


@triton.jit
def bf16_pair(p0,p1):
    u0=p0.to(tl.uint32,bitcast=True)
    u1=p1.to(tl.uint32,bitcast=True)
    r0=(u0+0x7fff+((u0>>16)&1))>>16
    r1=(u1+0x7fff+((u1>>16)&1))>>16
    return (r0|(r1<<16)).to(tl.int32,bitcast=True)


