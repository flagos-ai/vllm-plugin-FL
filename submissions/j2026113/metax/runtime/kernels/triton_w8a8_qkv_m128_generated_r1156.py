@triton.jit
def copy_stage(A,B,tid,by,bx,tile,M,N,K,head,stage:tl.constexpr,prime:tl.constexpr):
    row = tid >> 4
    p = (((tid & 15) - row + 16) & 15) * 16 + stage * 256
    dst = (tid >> 6) * 1024
    if prime:
        pred,bound = p,head
    else:
        pred,bound = tid*0,1
    for i in tl.static_range(4):
        a = tl.minimum(row + 16*i,M-by-1)
        publish(dst + i*4096 + stage*16384,A + (by+a)*K + tile*512+p,pred,bound)
    for i in tl.static_range(4):
        b = tl.minimum(row + 16*i,N-bx-1)
        publish(dst + 32768 + i*4096 + stage*16384,B + (bx+b)*K + tile*512+p,pred,bound)


