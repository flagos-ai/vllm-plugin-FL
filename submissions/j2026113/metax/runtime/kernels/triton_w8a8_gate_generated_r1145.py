from triton_w8a8_gate_support_r1145 import *
import triton
import triton.language as tl


@triton.jit
def w8a8_gate(A, B, Sa, Sb, C, M, N, K):
    tid = physical_thread_id(tl.arange(0, 256))
    wave = tid >> 6
    group = (tid >> 4) & 3
    lane = tid & 15
    by = tl.program_id(0) * 16
    bx = tl.program_id(1) * 128
    tail = (K - 1) // 256
    head = (K - 1) % 256 + 1
    ak = ((wave * 4 + group) ^ lane) * 16
    bk = lane * 16
    arow = by + tl.minimum(wave * 4 + group, M - by - 1)
    anext = A + arow * K + ak
    adst = wave * 1024
    bdst0 = 4096 + (wave * 16 + group + 0) * 256 + ((lane ^ (group + 0)) * 16)
    lds_a0 = lane * 256 + ((lane ^ (group + 0)) * 16)
    lds_b0 = 4096 + (wave * 16 + lane) * 256 + ((lane ^ (group + 0)) * 16)
    bp00 = B + (bx + tl.minimum(wave * 32 + group * 2 + 0, N - bx - 1)) * K + bk
    bp10 = B + (bx + tl.minimum(wave * 32 + group * 2 + 1, N - bx - 1)) * K + bk
    bdst1 = 4096 + (wave * 16 + group + 4) * 256 + ((lane ^ (group + 4)) * 16)
    lds_a1 = lane * 256 + ((lane ^ (group + 4)) * 16)
    lds_b1 = 4096 + (wave * 16 + lane) * 256 + ((lane ^ (group + 4)) * 16)
    bp01 = B + (bx + tl.minimum(wave * 32 + group * 2 + 8, N - bx - 1)) * K + bk
    bp11 = B + (bx + tl.minimum(wave * 32 + group * 2 + 9, N - bx - 1)) * K + bk
    bdst2 = 4096 + (wave * 16 + group + 8) * 256 + ((lane ^ (group + 8)) * 16)
    lds_a2 = lane * 256 + ((lane ^ (group + 8)) * 16)
    lds_b2 = 4096 + (wave * 16 + lane) * 256 + ((lane ^ (group + 8)) * 16)
    bp02 = B + (bx + tl.minimum(wave * 32 + group * 2 + 16, N - bx - 1)) * K + bk
    bp12 = B + (bx + tl.minimum(wave * 32 + group * 2 + 17, N - bx - 1)) * K + bk
    bdst3 = 4096 + (wave * 16 + group + 12) * 256 + ((lane ^ (group + 12)) * 16)
    lds_a3 = lane * 256 + ((lane ^ (group + 12)) * 16)
    lds_b3 = 4096 + (wave * 16 + lane) * 256 + ((lane ^ (group + 12)) * 16)
    bp03 = B + (bx + tl.minimum(wave * 32 + group * 2 + 24, N - bx - 1)) * K + bk
    bp13 = B + (bx + tl.minimum(wave * 32 + group * 2 + 25, N - bx - 1)) * K + bk
    p00_0,p00_1,p00_2,p00_3 = load_b_tail(bk, bp00 + tail * 256, head)
    p01_0,p01_1,p01_2,p01_3 = load_b_tail(bk, bp01 + tail * 256, head)
    p02_0,p02_1,p02_2,p02_3 = load_b_tail(bk, bp02 + tail * 256, head)
    p03_0,p03_1,p03_2,p03_3 = load_b_tail(bk, bp03 + tail * 256, head)
    publish(adst, anext + tail * 256, ak, head)
    p10_0,p10_1,p10_2,p10_3 = load_b_tail(bk, bp10 + tail * 256, head)
    p11_0,p11_1,p11_2,p11_3 = load_b_tail(bk, bp11 + tail * 256, head)
    p12_0,p12_1,p12_2,p12_3 = load_b_tail(bk, bp12 + tail * 256, head)
    p13_0,p13_1,p13_2,p13_3 = load_b_tail(bk, bp13 + tail * 256, head)
    store4(bdst0,p00_0,p00_1,p00_2,p00_3)
    store4(bdst1,p01_0,p01_1,p01_2,p01_3)
    store4(bdst2,p02_0,p02_1,p02_2,p02_3)
    store4(bdst3,p03_0,p03_1,p03_2,p03_3)
    wait_only(tid, 68)
    shared_barrier(tid)
    a_0,a_1,a_2,a_3 = load4(lds_a0)
    b0_0,b0_1,b0_2,b0_3 = load4(lds_b0)
    a_4,a_5,a_6,a_7 = load4(lds_a1)
    b0_4,b0_5,b0_6,b0_7 = load4(lds_b1)
    a_8,a_9,a_10,a_11 = load4(lds_a2)
    b0_8,b0_9,b0_10,b0_11 = load4(lds_b2)
    a_12,a_13,a_14,a_15 = load4(lds_a3)
    b0_12,b0_13,b0_14,b0_15 = load4(lds_b3)
    zero = tl.full((256,), 0, tl.int32)
    c0_0,c0_1,c0_2,c0_3 = zero,zero,zero,zero
    c1_0,c1_1,c1_2,c1_3 = zero,zero,zero,zero
    for tile_k in range(tail):
        p00_0,p00_1,p00_2,p00_3 = load_b_all(bp00 + tile_k * 256)
        c0_0,c0_1,c0_2,c0_3 = mma_i8(b0_0,a_0,c0_0,c0_1,c0_2,c0_3)
        a_8,a_9,a_10,a_11 = load4(lds_a2)
        c0_0,c0_1,c0_2,c0_3 = mma_i8(b0_1,a_1,c0_0,c0_1,c0_2,c0_3)
        b0_8,b0_9,b0_10,b0_11 = load4(lds_b2)
        c0_0,c0_1,c0_2,c0_3 = mma_i8(b0_2,a_2,c0_0,c0_1,c0_2,c0_3)
        p01_0,p01_1,p01_2,p01_3 = load_b_all(bp01 + tile_k * 256)
        c0_0,c0_1,c0_2,c0_3 = mma_i8(b0_3,a_3,c0_0,c0_1,c0_2,c0_3)
        c0_0,c0_1,c0_2,c0_3 = mma_i8(b0_4,a_4,c0_0,c0_1,c0_2,c0_3)
        a_12,a_13,a_14,a_15 = load4(lds_a3)
        c0_0,c0_1,c0_2,c0_3 = mma_i8(b0_5,a_5,c0_0,c0_1,c0_2,c0_3)
        p02_0,p02_1,p02_2,p02_3 = load_b_all(bp02 + tile_k * 256)
        c0_0,c0_1,c0_2,c0_3 = mma_i8(b0_6,a_6,c0_0,c0_1,c0_2,c0_3)
        b0_12,b0_13,b0_14,b0_15 = load4(lds_b3)
        c0_0,c0_1,c0_2,c0_3 = mma_i8(b0_7,a_7,c0_0,c0_1,c0_2,c0_3)
        c0_0,c0_1,c0_2,c0_3 = mma_i8(b0_8,a_8,c0_0,c0_1,c0_2,c0_3)
        p03_0,p03_1,p03_2,p03_3 = load_b_all(bp03 + tile_k * 256)
        c0_0,c0_1,c0_2,c0_3 = mma_i8(b0_9,a_9,c0_0,c0_1,c0_2,c0_3)
        wait_only(tid, 68)
        shared_barrier(tid)
        c0_0,c0_1,c0_2,c0_3 = mma_i8(b0_10,a_10,c0_0,c0_1,c0_2,c0_3)
        store4(bdst0,p10_0,p10_1,p10_2,p10_3)
        c0_0,c0_1,c0_2,c0_3 = mma_i8(b0_11,a_11,c0_0,c0_1,c0_2,c0_3)
        publish_a_all(adst, anext + tile_k * 256)
        store4(bdst1,p11_0,p11_1,p11_2,p11_3)
        c0_0,c0_1,c0_2,c0_3 = mma_i8(b0_12,a_12,c0_0,c0_1,c0_2,c0_3)
        store4(bdst2,p12_0,p12_1,p12_2,p12_3)
        c0_0,c0_1,c0_2,c0_3 = mma_i8(b0_13,a_13,c0_0,c0_1,c0_2,c0_3)
        store4(bdst3,p13_0,p13_1,p13_2,p13_3)
        c0_0,c0_1,c0_2,c0_3 = mma_i8(b0_14,a_14,c0_0,c0_1,c0_2,c0_3)
        p10_0,p10_1,p10_2,p10_3 = load_b_all(bp10 + tile_k * 256)
        c0_0,c0_1,c0_2,c0_3 = mma_i8(b0_15,a_15,c0_0,c0_1,c0_2,c0_3)
        wait_only(tid, 4096)
        b1_0,b1_1,b1_2,b1_3 = load4(lds_b0)
        b1_4,b1_5,b1_6,b1_7 = load4(lds_b1)
        c1_0,c1_1,c1_2,c1_3 = mma_i8(b1_0,a_0,c1_0,c1_1,c1_2,c1_3)
        b1_8,b1_9,b1_10,b1_11 = load4(lds_b2)
        c1_0,c1_1,c1_2,c1_3 = mma_i8(b1_1,a_1,c1_0,c1_1,c1_2,c1_3)
        p11_0,p11_1,p11_2,p11_3 = load_b_all(bp11 + tile_k * 256)
        c1_0,c1_1,c1_2,c1_3 = mma_i8(b1_2,a_2,c1_0,c1_1,c1_2,c1_3)
        b1_12,b1_13,b1_14,b1_15 = load4(lds_b3)
        c1_0,c1_1,c1_2,c1_3 = mma_i8(b1_3,a_3,c1_0,c1_1,c1_2,c1_3)
        c1_0,c1_1,c1_2,c1_3 = mma_i8(b1_4,a_4,c1_0,c1_1,c1_2,c1_3)
        p12_0,p12_1,p12_2,p12_3 = load_b_all(bp12 + tile_k * 256)
        c1_0,c1_1,c1_2,c1_3 = mma_i8(b1_5,a_5,c1_0,c1_1,c1_2,c1_3)
        c1_0,c1_1,c1_2,c1_3 = mma_i8(b1_6,a_6,c1_0,c1_1,c1_2,c1_3)
        c1_0,c1_1,c1_2,c1_3 = mma_i8(b1_7,a_7,c1_0,c1_1,c1_2,c1_3)
        p13_0,p13_1,p13_2,p13_3 = load_b_all(bp13 + tile_k * 256)
        c1_0,c1_1,c1_2,c1_3 = mma_i8(b1_8,a_8,c1_0,c1_1,c1_2,c1_3)
        wait_only(tid, 68)
        wait_only(tid, 4096)
        c1_0,c1_1,c1_2,c1_3 = mma_i8(b1_9,a_9,c1_0,c1_1,c1_2,c1_3)
        store4(bdst0,p00_0,p00_1,p00_2,p00_3)
        c1_0,c1_1,c1_2,c1_3 = mma_i8(b1_10,a_10,c1_0,c1_1,c1_2,c1_3)
        c1_0,c1_1,c1_2,c1_3 = mma_i8(b1_11,a_11,c1_0,c1_1,c1_2,c1_3)
        store4(bdst1,p01_0,p01_1,p01_2,p01_3)
        c1_0,c1_1,c1_2,c1_3 = mma_i8(b1_12,a_12,c1_0,c1_1,c1_2,c1_3)
        c1_0,c1_1,c1_2,c1_3 = mma_i8(b1_13,a_13,c1_0,c1_1,c1_2,c1_3)
        store4(bdst2,p02_0,p02_1,p02_2,p02_3)
        c1_0,c1_1,c1_2,c1_3 = mma_i8(b1_14,a_14,c1_0,c1_1,c1_2,c1_3)
        c1_0,c1_1,c1_2,c1_3 = mma_i8(b1_15,a_15,c1_0,c1_1,c1_2,c1_3)
        store4(bdst3,p03_0,p03_1,p03_2,p03_3)
        shared_barrier(tid)
        a_0,a_1,a_2,a_3 = load4(lds_a0)
        b0_0,b0_1,b0_2,b0_3 = load4(lds_b0)
        a_4,a_5,a_6,a_7 = load4(lds_a1)
        b0_4,b0_5,b0_6,b0_7 = load4(lds_b1)
    c0_0,c0_1,c0_2,c0_3 = mma_i8(b0_0,a_0,c0_0,c0_1,c0_2,c0_3)
    a_8,a_9,a_10,a_11 = load4(lds_a2)
    c0_0,c0_1,c0_2,c0_3 = mma_i8(b0_1,a_1,c0_0,c0_1,c0_2,c0_3)
    b0_8,b0_9,b0_10,b0_11 = load4(lds_b2)
    c0_0,c0_1,c0_2,c0_3 = mma_i8(b0_2,a_2,c0_0,c0_1,c0_2,c0_3)
    c0_0,c0_1,c0_2,c0_3 = mma_i8(b0_3,a_3,c0_0,c0_1,c0_2,c0_3)
    a_12,a_13,a_14,a_15 = load4(lds_a3)
    c0_0,c0_1,c0_2,c0_3 = mma_i8(b0_4,a_4,c0_0,c0_1,c0_2,c0_3)
    c0_0,c0_1,c0_2,c0_3 = mma_i8(b0_5,a_5,c0_0,c0_1,c0_2,c0_3)
    b0_12,b0_13,b0_14,b0_15 = load4(lds_b3)
    c0_0,c0_1,c0_2,c0_3 = mma_i8(b0_6,a_6,c0_0,c0_1,c0_2,c0_3)
    c0_0,c0_1,c0_2,c0_3 = mma_i8(b0_7,a_7,c0_0,c0_1,c0_2,c0_3)
    wait_only(tid, 64)
    wait_only(tid, 4096)
    c0_0,c0_1,c0_2,c0_3 = mma_i8(b0_8,a_8,c0_0,c0_1,c0_2,c0_3)
    store4(bdst0,p10_0,p10_1,p10_2,p10_3)
    c0_0,c0_1,c0_2,c0_3 = mma_i8(b0_9,a_9,c0_0,c0_1,c0_2,c0_3)
    c0_0,c0_1,c0_2,c0_3 = mma_i8(b0_10,a_10,c0_0,c0_1,c0_2,c0_3)
    store4(bdst1,p11_0,p11_1,p11_2,p11_3)
    c0_0,c0_1,c0_2,c0_3 = mma_i8(b0_11,a_11,c0_0,c0_1,c0_2,c0_3)
    c0_0,c0_1,c0_2,c0_3 = mma_i8(b0_12,a_12,c0_0,c0_1,c0_2,c0_3)
    store4(bdst2,p12_0,p12_1,p12_2,p12_3)
    c0_0,c0_1,c0_2,c0_3 = mma_i8(b0_13,a_13,c0_0,c0_1,c0_2,c0_3)
    store4(bdst3,p13_0,p13_1,p13_2,p13_3)
    c0_0,c0_1,c0_2,c0_3 = mma_i8(b0_14,a_14,c0_0,c0_1,c0_2,c0_3)
    wait_only(tid, 4096)
    b1_0,b1_1,b1_2,b1_3 = load4(lds_b0)
    c0_0,c0_1,c0_2,c0_3 = mma_i8(b0_15,a_15,c0_0,c0_1,c0_2,c0_3)
    b1_4,b1_5,b1_6,b1_7 = load4(lds_b1)
    c1_0,c1_1,c1_2,c1_3 = mma_i8(b1_0,a_0,c1_0,c1_1,c1_2,c1_3)
    c1_0,c1_1,c1_2,c1_3 = mma_i8(b1_1,a_1,c1_0,c1_1,c1_2,c1_3)
    c1_0,c1_1,c1_2,c1_3 = mma_i8(b1_2,a_2,c1_0,c1_1,c1_2,c1_3)
    b1_8,b1_9,b1_10,b1_11 = load4(lds_b2)
    c1_0,c1_1,c1_2,c1_3 = mma_i8(b1_3,a_3,c1_0,c1_1,c1_2,c1_3)
    c1_0,c1_1,c1_2,c1_3 = mma_i8(b1_4,a_4,c1_0,c1_1,c1_2,c1_3)
    c1_0,c1_1,c1_2,c1_3 = mma_i8(b1_5,a_5,c1_0,c1_1,c1_2,c1_3)
    b1_12,b1_13,b1_14,b1_15 = load4(lds_b3)
    c1_0,c1_1,c1_2,c1_3 = mma_i8(b1_6,a_6,c1_0,c1_1,c1_2,c1_3)
    c1_0,c1_1,c1_2,c1_3 = mma_i8(b1_7,a_7,c1_0,c1_1,c1_2,c1_3)
    c1_0,c1_1,c1_2,c1_3 = mma_i8(b1_8,a_8,c1_0,c1_1,c1_2,c1_3)
    c1_0,c1_1,c1_2,c1_3 = mma_i8(b1_9,a_9,c1_0,c1_1,c1_2,c1_3)
    c1_0,c1_1,c1_2,c1_3 = mma_i8(b1_10,a_10,c1_0,c1_1,c1_2,c1_3)
    c1_0,c1_1,c1_2,c1_3 = mma_i8(b1_11,a_11,c1_0,c1_1,c1_2,c1_3)
    c1_0,c1_1,c1_2,c1_3 = mma_i8(b1_12,a_12,c1_0,c1_1,c1_2,c1_3)
    c1_0,c1_1,c1_2,c1_3 = mma_i8(b1_13,a_13,c1_0,c1_1,c1_2,c1_3)
    c1_0,c1_1,c1_2,c1_3 = mma_i8(b1_14,a_14,c1_0,c1_1,c1_2,c1_3)
    c1_0,c1_1,c1_2,c1_3 = mma_i8(b1_15,a_15,c1_0,c1_1,c1_2,c1_3)
    col = bx + wave * 32 + 2 * lane
    row = by + group * 4
    sb = scale_pair((col < N).to(tl.int32), Sb + col)
    sb0, sb1 = low32(sb), high32(sb)
    sa0 = scale_one((row + 0 < M).to(tl.int32), Sa + row + 0)
    sa1 = scale_one((row + 1 < M).to(tl.int32), Sa + row + 1)
    sa2 = scale_one((row + 2 < M).to(tl.int32), Sa + row + 2)
    sa3 = scale_one((row + 3 < M).to(tl.int32), Sa + row + 3)
    packed0 = epilogue(c0_0,c1_0,sa0,sb0,sb1)
    packed1 = epilogue(c0_1,c1_1,sa1,sb0,sb1)
    packed2 = epilogue(c0_2,c1_2,sa2,sb0,sb1)
    packed3 = epilogue(c0_3,c1_3,sa3,sb0,sb1)
    publish_result(((row + 0 < M) & (col < N)).to(tl.int32), C + (row + 0) * N + col, packed0)
    publish_result(((row + 1 < M) & (col < N)).to(tl.int32), C + (row + 1) * N + col, packed1)
    publish_result(((row + 2 < M) & (col < N)).to(tl.int32), C + (row + 2) * N + col, packed2)
    publish_result(((row + 3 < M) & (col < N)).to(tl.int32), C + (row + 3) * N + col, packed3)

bind_gate(w8a8_gate)
