"""
Extract torch.ops._C schema strings from vLLM's C++ source and write them to
vllm_fl/ops/_C_ops_schemas.py.

Run this script whenever vLLM is upgraded so the bundled schemas stay in sync:

    python tools/generate_op_schemas.py

The script auto-detects the vLLM source tree from the installed package. If
vLLM was installed in editable mode the csrc/ directory is next to the package;
otherwise pass the path explicitly:

    python tools/generate_op_schemas.py /path/to/vllm
"""

import ast
import hashlib
import re
import sys
from pathlib import Path


def extract_schemas(vllm_root: Path) -> list[str]:
    """Extract only _C definitions, excluding _C_cache_ops and implementations."""
    source_files = [
        vllm_root / "csrc" / "torch_bindings.cpp",
        vllm_root / "csrc" / "libtorch_stable" / "torch_bindings.cpp",
    ]
    # Preserve strings while stripping C++ comments before matching braces.
    token = re.compile(r'"(?:\\.|[^"\\])*"|//[^\n]*|/\*.*?\*/', re.DOTALL)
    block = re.compile(
        r"\b(?:STABLE_)?TORCH_LIBRARY(?:_FRAGMENT)?\(\s*_C\s*,\s*(\w+)\s*\)\s*\{"
    )
    schemas: dict[str, str] = {}
    for path in source_files:
        if not path.is_file():
            continue
        content = token.sub(
            lambda m: m.group(0) if m.group(0).startswith('"') else " ",
            path.read_text(),
        )
        for match in block.finditer(content):
            start = match.end()
            depth = 1
            end = start
            in_string = False
            escaped = False
            while end < len(content) and depth:
                char = content[end]
                if in_string:
                    if escaped:
                        escaped = False
                    elif char == "\\":
                        escaped = True
                    elif char == '"':
                        in_string = False
                elif char == '"':
                    in_string = True
                elif char == "{":
                    depth += 1
                elif char == "}":
                    depth -= 1
                end += 1
            if depth:
                raise ValueError(f"Unclosed _C registration block in {path}")
            definition = re.compile(
                rf'\b{re.escape(match.group(1))}\.def\(\s*'
                r'((?:"(?:\\.|[^"\\])*"\s*)+)'
            )
            for item in definition.finditer(content[start:end - 1]):
                strings = re.findall(r'"(?:\\.|[^"\\])*"', item.group(1))
                schema = "".join(ast.literal_eval(value) for value in strings)
                schema = re.sub(r"\s+", " ", schema).strip()
                full_name = schema.split("(", 1)[0]
                if full_name in schemas and schemas[full_name] != schema:
                    raise ValueError(f"Conflicting source schemas for {full_name}")
                schemas[full_name] = schema
    return list(schemas.values())


def main() -> None:
    if len(sys.argv) > 1:
        vllm_root = Path(sys.argv[1])
    else:
        import vllm

        vllm_root = Path(vllm.__file__).resolve().parent.parent

    schemas = extract_schemas(vllm_root)
    if not schemas:
        print(f"ERROR: no schemas found under {vllm_root}/csrc/", file=sys.stderr)
        sys.exit(1)

    out = (
        Path(__file__).resolve().parent.parent / "vllm_fl" / "ops" / "_C_ops_schemas.py"
    )
    source_hashes = {
        str(path.relative_to(vllm_root)): hashlib.sha256(path.read_bytes()).hexdigest()
        for path in (vllm_root / "csrc" / "torch_bindings.cpp",
                     vllm_root / "csrc" / "libtorch_stable" / "torch_bindings.cpp")
        if path.is_file()
    }
    lines = [
        "# Auto-generated by tools/generate_op_schemas.py — do not edit.",
        "# Schema declarations only: implementations are not provided by this list.",
        "SOURCE_SHA256 = " + repr(source_hashes),
        "",
        "SCHEMAS: list[str] = [",
    ]
    for s in schemas:
        lines.append(f"    {repr(s)},")
    lines.append("]")
    lines.append("")
    out.write_text("\n".join(lines))
    print(f"Wrote {len(schemas)} schemas to {out}")


if __name__ == "__main__":
    main()
